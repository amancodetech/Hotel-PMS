export class IdentityError extends Error {
  readonly code: IdentityErrorCode;
  readonly status: number;
  readonly details: Record<string, unknown>;

  constructor(code: IdentityErrorCode, details: Record<string, unknown> = {}) {
    super(code);
    this.name = 'IdentityError';
    this.code = code;
    this.status = statusByCode[code] ?? 400;
    this.details = details;
  }
}

export function identityErrorStatus(code: string): number | null {
  return statusByCode[code as IdentityErrorCode] ?? null;
}
