export class PropertyError extends Error {
  readonly code: PropertyErrorCode;
  readonly status: number;
  readonly details: Record<string, unknown>;

  constructor(code: PropertyErrorCode, details: Record<string, unknown> = {}) {
    super(code);
    this.name = 'PropertyError';
    this.code = code;
    this.status = statusByCode[code];
    this.details = details;
  }
}

export function isPropertyErrorCode(value: string): value is PropertyErrorCode {
  return Object.hasOwn(statusByCode, value);
}
